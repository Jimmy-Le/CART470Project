import express from "express";
import mongoose from "mongoose";
import multer from 'multer';
import {GridFsStorage} from 'multer-gridfs-storage';
import Audio from "../models/Audio.mjs";
import dotenv from "dotenv";

// MUST be called before process.env is accessed
dotenv.config();

const router = express.Router();
const mongoURI = process.env.MONGODB_URI;   // Pull the URI from the .env file

// 1. GridFS Configuration
const storage = new GridFsStorage({
  url: mongoURI,
  file: (req, file) => {
    return {
      filename: `audio-${Date.now()}-${file.originalname}`,
      bucketName: 'audioFiles' 
    };
  }
});

const upload = multer({ storage });

// 2. The Route
router.post('/', upload.single('audioData'), async (req, res) => {
  try {
    // req.file is created by GridFS. req.body is sent from your React form.
    
    // Create the Mongoose document using the ID generated by GridFS
    const newAudio = new Audio({
      name: req.body.audioName,      // Text from React FormData
      gridFsId: req.file.id,         // ID from GridFS
    });

    // Save your custom model to the database
    await newAudio.save();

    res.json({ 
      message: 'Audio and model saved successfully', 
      audioDocument: newAudio 
    });
    
  } catch (error) {
    console.error(error);
    res.status(500).json({ message: 'Error saving audio model' });
  }
});

// ==========================================
// ROUTE 1: GET ALL AUDIO FILES (The metadata)
// Path: /api/audio/
// ==========================================
router.get('/', async (req, res) => {
  try {
    // Find all audio documents and sort them by newest first
    const audioList = await Audio.find().sort({ createdAt: -1 });
    res.json(audioList);
  } catch (error) {
    console.error("Error fetching audio list:", error);
    res.status(500).json({ message: 'Failed to fetch audio files' });
  }
});


// GET route to stream audio by its GridFS ID
router.get('/:gridFsId', async (req, res) => {
  try {
    const requestedId = req.params.gridFsId;
    console.log("React is requesting audio with ID:", requestedId); // <-- Check this in your terminal

    // 1. Check if the ID is a valid MongoDB format before converting it
    if (!mongoose.Types.ObjectId.isValid(requestedId)) {
      console.error(`Error: '${requestedId}' is not a valid MongoDB ID format.`);
      return res.status(400).json({ message: 'Invalid Audio ID format' });
    }


    // 1. Access the underlying MongoDB database connection via Mongoose
    const db = mongoose.connection.db;
    
    // 2. Initialize a GridFSBucket. 
    // The bucketName MUST match the one you set in your GridFsStorage config.
    const bucket = new mongoose.mongo.GridFSBucket(db, {
      bucketName: 'audioFiles' 
    });

    // 3. Convert the ID from the URL into a MongoDB ObjectId
    const fileId = new mongoose.Types.ObjectId(req.params.gridFsId);

    // 4. Verify the file exists in the database
    const files = await bucket.find({ _id: fileId }).toArray();
    if (files.length === 0) {
      return res.status(404).json({ message: 'Audio file not found' });
    }

    // 5. Tell the browser what kind of file is coming
    res.set('Content-Type', files[0].contentType || 'audio/mpeg');
    res.set('Accept-Ranges', 'bytes'); // Allows the browser to scrub forward/backward in the audio player

    // 6. Open a download stream and pipe it directly to the response
    const downloadStream = bucket.openDownloadStream(fileId);
    downloadStream.pipe(res);

  } catch (error) {
    console.error("Error streaming audio:", error);
    res.status(500).json({ message: 'Internal server error' });
  }
});


export default router;